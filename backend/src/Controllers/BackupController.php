<?php
declare(strict_types=1);

namespace GulfTaxis\Controllers;

use GulfTaxis\Config\Database;
use GulfTaxis\Middleware\AuthMiddleware;
use GulfTaxis\Middleware\RoleMiddleware;
use GulfTaxis\Utils\Response;
use PDO;

class BackupController
{
    private string $backupDir;

    public function __construct()
    {
        // Store backups safely outside the public document root
        $this->backupDir = dirname(__DIR__, 2) . '/storage/backups';
        if (!is_dir($this->backupDir)) {
            mkdir($this->backupDir, 0750, true);
        }
    }

    public function index(): void
    {
        $user = AuthMiddleware::authenticate();
        RoleMiddleware::requireAdmin($user);

        $backups = [];
        $files = glob($this->backupDir . '/*.sql');
        if ($files) {
            foreach ($files as $file) {
                $backups[] = [
                    'filename' => basename($file),
                    'size_bytes' => filesize($file),
                    'size_formatted' => round(filesize($file) / 1024, 2) . ' KB',
                    'created_at' => date('Y-m-d H:i:s', filemtime($file)),
                    'status' => 'Verified'
                ];
            }
            // Sort newest first
            usort($backups, fn($a, $b) => strcmp($b['created_at'], $a['created_at']));
        }

        Response::success($backups);
    }

    public function create(): void
    {
        $user = AuthMiddleware::authenticate();
        RoleMiddleware::requireAdmin($user);
        $db = Database::getConnection();

        $timestamp = date('Y-m-d_H-i-s');
        $filename = "gulftaxis_backup_{$timestamp}.sql";
        $filepath = $this->backupDir . '/' . $filename;

        // Generate genuine SQL dump directly via PDO
        $tables = ['schema_migrations', 'system_settings', 'users', 'drivers', 'vehicles', 'bookings', 'booking_assignments', 'audit_logs', 'password_reset_tokens'];

        $sqlDump = "-- ====================================================================\n";
        $sqlDump .= "-- GULF TAXIS DISPATCH CLOUD - DATABASE BACKUP\n";
        $sqlDump .= "-- Generated: " . date('Y-m-d H:i:s') . "\n";
        $sqlDump .= "-- Generated By: " . htmlspecialchars($user['full_name']) . " (" . htmlspecialchars($user['email']) . ")\n";
        $sqlDump .= "-- Hostinger Compatible MySQL/MariaDB Dump\n";
        $sqlDump .= "-- ====================================================================\n\n";
        $sqlDump .= "SET FOREIGN_KEY_CHECKS = 0;\n";
        $sqlDump .= "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n";
        $sqlDump .= "SET time_zone = \"+00:00\";\n\n";

        foreach ($tables as $table) {
            // Check if table exists
            $check = $db->query("SHOW TABLES LIKE '{$table}'")->fetch();
            if (!$check) continue;

            $sqlDump .= "-- Table structure for `{$table}`\n";
            $sqlDump .= "DROP TABLE IF EXISTS `{$table}`;\n";
            $createTable = $db->query("SHOW CREATE TABLE `{$table}`")->fetchColumn(1);
            $sqlDump .= $createTable . ";\n\n";

            // Dump data
            $rows = $db->query("SELECT * FROM `{$table}`")->fetchAll(PDO::FETCH_ASSOC);
            if (!empty($rows)) {
                $sqlDump .= "-- Dumping data for `{$table}` (" . count($rows) . " rows)\n";
                $columns = array_keys($rows[0]);
                $colNames = implode('`, `', $columns);

                foreach (array_chunk($rows, 50) as $chunk) {
                    $sqlDump .= "INSERT INTO `{$table}` (`{$colNames}`) VALUES\n";
                    $valueLines = [];
                    foreach ($chunk as $row) {
                        $values = array_map(function ($val) use ($db) {
                            if ($val === null) return 'NULL';
                            return $db->quote((string)$val);
                        }, array_values($row));
                        $valueLines[] = "(" . implode(', ', $values) . ")";
                    }
                    $sqlDump .= implode(",\n", $valueLines) . ";\n";
                }
                $sqlDump .= "\n";
            }
        }

        $sqlDump .= "SET FOREIGN_KEY_CHECKS = 1;\n";
        $sqlDump .= "-- END OF GULF TAXIS DISPATCH CLOUD BACKUP\n";

        $bytesWritten = file_put_contents($filepath, $sqlDump);

        if ($bytesWritten === false || !file_exists($filepath) || filesize($filepath) === 0) {
            Response::error('Failed to create backup file on server storage. Check write permissions.', 500);
            return;
        }

        // Record Audit Log
        $auditStmt = $db->prepare('INSERT INTO audit_logs (user_id, action, entity_type, entity_id, ip_address, details_json) VALUES (:uid, "DATABASE_BACKUP_CREATED", "system", NULL, :ip, :det)');
        $auditStmt->execute([
            'uid' => $user['id'],
            'ip'  => $_SERVER['REMOTE_ADDR'] ?? '0.0.0.0',
            'det' => json_encode(['filename' => $filename, 'bytes' => $bytesWritten])
        ]);

        Response::success([
            'filename' => $filename,
            'size_bytes' => $bytesWritten,
            'size_formatted' => round($bytesWritten / 1024, 2) . ' KB',
            'created_at' => date('Y-m-d H:i:s'),
            'status' => 'Verified'
        ], 'Database backup generated and verified successfully.');
    }

    public function download(): void
    {
        $user = AuthMiddleware::authenticate();
        RoleMiddleware::requireAdmin($user);

        $filename = basename($_GET['file'] ?? '');
        if (empty($filename) || !preg_match('/^gulftaxis_backup_[a-zA-Z0-9_\-]+\.sql$/', $filename)) {
            Response::error('Invalid backup filename specified.', 400);
            return;
        }

        $filepath = $this->backupDir . '/' . $filename;
        if (!file_exists($filepath)) {
            Response::error('Backup file not found on server.', 404);
            return;
        }

        header('Content-Description: File Transfer');
        header('Content-Type: application/sql');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Expires: 0');
        header('Cache-Control: must-revalidate');
        header('Pragma: public');
        header('Content-Length: ' . filesize($filepath));
        readfile($filepath);
        exit;
    }
}
